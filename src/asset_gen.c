#pragma pack(push, 1)
struct CURHeader {
    uint16_t zero;
    uint16_t type;
    uint16_t count;
    uint8_t width;
    uint8_t height;
    uint8_t colors;
    uint8_t res;
    uint16_t hot_x;
    uint16_t hot_y;
    uint32_t size;
    uint32_t offset;
};
struct DIBHeader {
    uint32_t dib_size;
    int32_t width;
    int32_t height;
    uint16_t planes;
    uint16_t bpp;
    uint32_t comp;
    uint32_t img_size;
};
#pragma pack(pop)

void generate_cursors(void) {
    printf("  [Native Asset Gen] Generating cursors from .cur...\n");
    
    const char *cur_path = "assets/cursor.cur";
    FILE *f = fopen(cur_path, "rb");
    if (!f) {
        system("unzip -o arkrt/ArkGraphics/mousecursorpack.zip -d /tmp/ >/dev/null 2>&1");
        cur_path = "/tmp/cursor.cur"; // Adjust based on actual zip contents
        f = fopen(cur_path, "rb");
        if (!f) return;
    }
    
    fseek(f, 0, SEEK_END);
    size_t sz = ftell(f);
    fseek(f, 0, SEEK_SET);
    
    uint8_t *data = malloc(sz);
    fread(data, 1, sz, f);
    fclose(f);
    
    struct CURHeader *hdr = (struct CURHeader *)data;
    if (hdr->type != 2) {
        printf("ERROR: Not a CUR file\n");
        free(data);
        return;
    }
    
    struct DIBHeader *dib = (struct DIBHeader *)(data + hdr->offset);
    int w = dib->width;
    int h = dib->height / 2;
    
    if (dib->bpp != 32) {
        printf("ERROR: Only 32bpp cursors supported\n");
        free(data);
        return;
    }
    
    uint8_t *pixels = data + hdr->offset + dib->dib_size;
    
    FILE *out = fopen("arkrt/ArkGraphics/ArkCursor.swift", "w");
    if (!out) { free(data); return; }
    
    fprintf(out, "// Auto-generated by aake cursor-gen\n");
    fprintf(out, "let cursorWidth = %d\n", w);
    fprintf(out, "let cursorHeight = %d\n", h);
    fprintf(out, "let cursorHotX = %d\n", hdr->hot_x);
    fprintf(out, "let cursorHotY = %d\n", hdr->hot_y);
    fprintf(out, "let cursorData: [UInt32] = [\n");
    
    for (int i = h - 1; i >= 0; i--) {
        uint8_t *row = pixels + (i * w * 4);
        for (int j = 0; j < w; j++) {
            uint8_t b = row[j*4 + 0];
            uint8_t g = row[j*4 + 1];
            uint8_t r = row[j*4 + 2];
            uint8_t a = row[j*4 + 3];
            uint32_t pixel = (a << 24) | (r << 16) | (g << 8) | b;
            fprintf(out, "0x%08X, ", pixel);
        }
        fprintf(out, "\n");
    }
    
    fprintf(out, "]\n");
    fclose(out);
    free(data);
    
    printf("  [Native Asset Gen] Cursors generated successfully.\n");
}
